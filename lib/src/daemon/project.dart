import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

import '../cli/common.dart';

/// A Flutter project that `flute run` launches.
class FlutterProject {
  FlutterProject._(this.directory, this.name);

  /// Finds the project that contains [start] by looking for `pubspec.yaml`.
  static FlutterProject find(String start) {
    Directory dir = Directory(p.absolute(start));
    while (true) {
      final pubspec = File(p.join(dir.path, 'pubspec.yaml'));
      if (pubspec.existsSync()) {
        final RegExpMatch? match = RegExp(
          r'^name:\s*([A-Za-z0-9_]+)',
          multiLine: true,
        ).firstMatch(pubspec.readAsStringSync());
        if (match == null) {
          throw FluteException('${pubspec.path} has no name.');
        }
        return FlutterProject._(dir.path, match[1]!);
      }
      final Directory parent = dir.parent;
      if (parent.path == dir.path) {
        throw FluteException(
          'No Flutter project found in ${p.absolute(start)}.',
          hint: 'Run flute from inside the app\'s project.',
        );
      }
      dir = parent;
    }
  }

  final String directory;
  final String name;

  /// Fails with the fix if the project does not depend on `flutter_flute`.
  void checkDependency() {
    final config = File(p.join(directory, '.dart_tool', 'package_config.json'));
    final bool found;
    if (config.existsSync()) {
      final Object? decoded = jsonDecode(config.readAsStringSync());
      final List<Object?> packages =
          (decoded! as Map<String, Object?>)['packages'] as List<Object?>? ?? const <Object?>[];
      found = packages.any(
        (Object? package) => (package! as Map<String, Object?>)['name'] == 'flutter_flute',
      );
    } else {
      // No pub get yet; `flutter run` will run it. Check the pubspec instead.
      found = RegExp(
        r'^\s+flutter_flute:',
        multiLine: true,
      ).hasMatch(File(p.join(directory, 'pubspec.yaml')).readAsStringSync());
    }
    if (!found) {
      throw FluteException(
        '$name does not depend on flutter_flute.',
        hint: 'Run: flutter pub add --dev flutter_flute',
      );
    }
  }

  /// Writes the wrapper entrypoint for [target] and returns its path,
  /// relative to the project.
  String writeEntrypoint(String target) {
    final String targetPath = p.normalize(p.absolute(directory, target));
    final targetFile = File(targetPath);
    if (!targetFile.existsSync()) {
      throw FluteException('Target $target does not exist.', exitCode: ExitCode.usage);
    }
    final String outDir = p.join(directory, '.dart_tool', 'flute');
    Directory(outDir).createSync(recursive: true);
    final String source = generateEntrypoint(
      importUri: importUriFor(targetPath, outDir),
      mainSource: targetFile.readAsStringSync(),
    );
    File(p.join(outDir, 'main.dart')).writeAsStringSync(source);
    return p.join('.dart_tool', 'flute', 'main.dart');
  }

  /// A `package:` URI for targets under `lib/`, otherwise a path relative to
  /// [fromDir].
  String importUriFor(String targetPath, String fromDir) {
    final String lib = p.join(directory, 'lib');
    if (p.isWithin(lib, targetPath)) {
      return 'package:$name/${p.posix.joinAll(p.split(p.relative(targetPath, from: lib)))}';
    }
    return p.posix.joinAll(p.split(p.relative(targetPath, from: fromDir)));
  }
}

final RegExp _mainDeclaration = RegExp(
  r'^\s*(?:(Future|FutureOr)\s*(?:<[^>]*>)?\s+|void\s+|dynamic\s+)?main\s*\(([^)]*)\)\s*(async)?',
  multiLine: true,
);

/// Generates the wrapper entrypoint source.
///
/// Reads [mainSource]'s `main` declaration to pass `args` when `main` takes
/// them, and to await it when it is asynchronous.
String generateEntrypoint({required String importUri, required String mainSource}) {
  final RegExpMatch? match = _mainDeclaration.firstMatch(mainSource);
  final bool takesArgs = match != null && match[2]!.trim().isNotEmpty;
  final bool isAsync = match != null && (match[1] != null || match[3] != null);
  final String call = 'app.main(${takesArgs ? 'args' : ''})';
  final String body = isAsync ? '  await $call;' : '  $call;';
  return '''
// GENERATED by flute. Do not edit.
import 'package:flutter_flute/flutter_flute.dart';
import '$importUri' as app;

${isAsync ? 'Future<void> main(List<String> args) async {' : 'void main(List<String> args) {'}
  enableFlute();
$body
}
''';
}
